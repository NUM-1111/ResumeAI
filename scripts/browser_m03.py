"""Synthetic personal-material browser acceptance, no model calls."""
import uuid
from pathlib import Path
from playwright.sync_api import sync_playwright, expect


def verify(port, password):
    with sync_playwright() as pw:
        browser = pw.chromium.launch(headless=True,args=['--no-sandbox'])
        context = browser.new_context(viewport={'width':1440,'height':1000})
        font=Path('/mnt/c/Windows/Fonts/msyh.ttc')
        if font.is_file():
            context.route('**/__test_font',lambda route:route.fulfill(body=font.read_bytes(),content_type='font/collection'))
            context.add_init_script("document.addEventListener('DOMContentLoaded',()=>{const s=document.createElement('style');s.textContent=\"@font-face{font-family:T;src:url('/__test_font')}body,input,textarea,button{font-family:T,system-ui!important}\";document.head.append(s);});")
        page = context.new_page()
        page.set_default_timeout(5000)
        errors=[]
        page.on('pageerror',lambda error:errors.append(str(error)))
        page.goto('http://127.0.0.1:'+str(port))
        page.get_by_label('口令',exact=True).fill(password)
        page.get_by_role('button',name='登录',exact=True).click()
        page.get_by_role('button',name='＋新建档案').click()
        page.get_by_label('档案名称',exact=True).fill('材料体验-'+uuid.uuid4().hex[:8])
        page.get_by_role('button',name='创建',exact=True).click()
        page.get_by_role('button',name='个人材料',exact=True).click()
        page.get_by_role('button',name='＋添加个人材料').click()
        page.get_by_label('材料名称',exact=True).fill('项目说明')
        page.get_by_label('材料粘贴文本',exact=True).fill('合成经历：协助部署。')
        page.get_by_role('button',name='保存个人材料',exact=True).click()
        expect(page.get_by_label('材料正文',exact=True)).to_have_value('合成经历：协助部署。')
        expect(page.get_by_text('由粘贴文本创建，无原件。',exact=True)).to_be_visible()
        page.get_by_role('button',name='重命名材料',exact=True).click()
        page.get_by_label('新的材料名称',exact=True).fill('更名说明')
        page.get_by_role('button',name='保存材料修改',exact=True).click()
        expect(page.get_by_role('heading',name='更名说明',exact=True)).to_be_visible()
        page.get_by_role('button',name='编辑材料文本',exact=True).click()
        page.get_by_label('编辑材料文本',exact=True).fill('手工修正的共享材料')
        page.get_by_role('button',name='保存材料修改',exact=True).click()
        expect(page.get_by_label('材料正文',exact=True)).to_have_value('手工修正的共享材料')
        expect(page.get_by_role('button',name='返回工作区列表',exact=True)).to_be_enabled()
        page.get_by_role('button',name='返回工作区列表',exact=True).click()
        page.get_by_role('button',name='＋新建工作区',exact=True).click()
        page.get_by_label('工作区名称',exact=True).fill('引用区')
        page.get_by_label('岗位方向',exact=True).fill('Java')
        page.get_by_role('button',name='创建',exact=True).click()
        expect(page.get_by_label('粘贴简历文本',exact=True)).to_be_visible()
        page.get_by_role('button',name='个人材料',exact=True).click()
        page.get_by_role('button',name='更名说明',exact=True).click()
        expect(page.get_by_role('checkbox')).not_to_be_checked()
        page.get_by_role('checkbox').check()
        page.get_by_role('button',name='保存参考去向',exact=True).click()
        expect(page.get_by_text('本区参考中',exact=True)).to_be_visible()
        expect(page.locator('aside')).to_contain_text('本区参考材料：1 份')
        page.get_by_role('checkbox').uncheck()
        page.get_by_role('button',name='保存参考去向',exact=True).click()
        expect(page.get_by_text('本区参考中',exact=True)).to_have_count(0)
        expect(page.locator('aside')).to_contain_text('本区参考材料：0 份')
        page.get_by_role('button',name='＋添加个人材料').click()
        page.get_by_label('选择材料文件',exact=True).set_input_files({'name':'补充资料.txt','mimeType':'text/plain','buffer':'文件原文：辅助项目经历'.encode()})
        expect(page.get_by_role('checkbox')).not_to_be_checked()
        page.get_by_role('checkbox').check()
        # Material creation succeeds, but reference persistence fails once.
        page.route('**/references/*',lambda route:route.abort() if route.request.method=='PUT' else route.continue_())
        page.get_by_role('button',name='保存个人材料',exact=True).click()
        expect(page.get_by_text('材料已保存，部分参考设置失败',exact=False)).to_be_visible()
        expect(page.get_by_label('材料正文',exact=True)).to_have_value('文件原文：辅助项目经历')
        page.unroute('**/references/*')
        page.get_by_role('button',name='保存参考去向',exact=True).click()
        expect(page.get_by_text('本区参考中',exact=True)).to_be_visible()
        with page.expect_download() as downloaded:
            page.get_by_role('link',name='打开/下载材料原件',exact=True).click()
        assert Path(downloaded.value.path()).read_bytes()=='文件原文：辅助项目经历'.encode()
        page.evaluate('document.fonts.ready')
        page.screenshot(path='/root/java/ResumeAI/.local/m03-desktop.png',full_page=True)
        page.set_viewport_size({'width':390,'height':900})
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
        page.screenshot(path='/root/java/ResumeAI/.local/m03-mobile.png',full_page=True)
        assert not errors,errors
        browser.close()
    print('PASS: M03 materials without workspace, rename/edit, explicit reference/removal and narrow viewport')