"""Draft and context controls on real APIs, no model key or model invocation."""
import uuid
from playwright.sync_api import sync_playwright, expect


def verify(port,password):
    with sync_playwright() as pw:
        browser=pw.chromium.launch(headless=True,args=['--no-sandbox'])
        context=browser.new_context(viewport={'width':1440,'height':1000})
        page=context.new_page();page.set_default_timeout(7000)
        page.goto('http://127.0.0.1:'+str(port))
        page.get_by_label('口令',exact=True).fill(password)
        page.get_by_role('button',name='登录',exact=True).click()
        page.get_by_role('button',name='＋新建档案').click()
        page.get_by_label('档案名称',exact=True).fill('草稿合成-'+uuid.uuid4().hex[:8])
        page.get_by_role('button',name='创建',exact=True).click()
        page.get_by_role('button',name='＋新建工作区').click()
        page.get_by_label('工作区名称',exact=True).fill('草稿区')
        page.get_by_label('岗位方向',exact=True).fill('Java')
        page.get_by_role('button',name='创建',exact=True).click()
        draft=page.get_by_label('向 AI 提问',exact=True)
        draft.fill('不发给模型的合成草稿')
        expect(page.get_by_text('草稿已保存',exact=True)).to_be_visible()
        page.reload()
        expect(draft).to_have_value('不发给模型的合成草稿')
        page.get_by_role('button',name='对话菜单',exact=True).click()
        page.once('dialog',lambda dialog:dialog.accept())
        page.get_by_role('button',name='不携带此前聊天，继续对话',exact=True).click()
        expect(page.get_by_text('已建立分隔点，后续不携带此前聊天。',exact=True)).to_be_visible()
        expect(draft).to_have_value('不发给模型的合成草稿')
        page.get_by_role('button',name='对话菜单',exact=True).click()
        page.once('dialog',lambda dialog:dialog.accept())
        page.get_by_role('button',name='清空记录并开始新对话',exact=True).click()
        expect(draft).to_have_value('')
        page.reload();expect(draft).to_have_value('')
        page.route('**/draft',lambda route:route.abort() if route.request.method=='PUT' else route.continue_())
        draft.fill('保存失败仍保留')
        expect(page.get_by_text('刷新或关闭可能丢失未保存文字',exact=False)).to_be_visible()
        expect(draft).to_have_value('保存失败仍保留')
        page.unroute('**/draft')
        page.get_by_role('button',name='重试保存草稿',exact=True).click()
        expect(page.get_by_text('草稿已保存',exact=True)).to_be_visible()
        page.reload();expect(draft).to_have_value('保存失败仍保留')
        other=context.new_page();other.set_default_timeout(7000)
        other.goto('http://127.0.0.1:'+str(port))
        expect(other.get_by_label('向 AI 提问',exact=True)).to_have_value('保存失败仍保留')
        other.get_by_role('button',name='对话菜单',exact=True).click()
        other.once('dialog',lambda dialog:dialog.accept())
        other.get_by_role('button',name='清空记录并开始新对话',exact=True).click()
        expect(other.get_by_label('向 AI 提问',exact=True)).to_have_value('')
        expect(page.get_by_role('button',name='核对别处草稿',exact=True)).to_be_visible()
        expect(draft).to_have_value('保存失败仍保留')
        draft.fill('别页清空后本页未确认输入')
        # Editing does not auto-resurrect a cleared draft; new tab still reads the empty saved draft.
        other.reload()
        expect(other.get_by_label('向 AI 提问',exact=True)).to_have_value('')
        other.close()
        # A delayed admission response must not erase text entered meanwhile.
        page.once('dialog',lambda dialog:dialog.accept())
        page.reload()
        expect(draft).to_have_value('')
        page.route('**/model',lambda route:route.fulfill(json={'configured':True}))
        page.reload()
        page.get_by_role('button',name='参考资料',exact=True).click()
        page.get_by_label('参考工作区简历',exact=True).uncheck()
        page.get_by_role('button',name='完成',exact=True).click()
        page.route('**/conversation',lambda route:route.fulfill(json={'id':'browser-synthetic','message':'延迟受理问题','answer':None,'execution_status':'CALLING','record_status':'PENDING','error_code':None,'model':'test'},status=202) if route.request.method=='POST' else route.continue_())
        page.evaluate('''() => {
          const original=window.fetch.bind(window);
          window.fetch=async (...args)=>{const response=await original(...args);
            if(args[1]?.method==='POST'&&String(args[0]).endsWith('/conversation'))
              await new Promise(resolve=>setTimeout(resolve,1200));
            return response;};
        }''')
        draft.fill('延迟受理问题')
        page.get_by_role('button',name='发送',exact=True).click()
        expect(page.get_by_role('button',name='正在受理…',exact=True)).to_be_visible()
        draft.fill('回答期间的新草稿')
        expect(page.get_by_role('button',name='正在受理…',exact=True)).to_have_count(0)
        expect(draft).to_have_value('回答期间的新草稿')
        expect(page.get_by_text('草稿已保存',exact=True)).to_be_visible()
        page.reload();expect(draft).to_have_value('回答期间的新草稿')
        browser.close()
    print('PASS: M05 draft persistence, boundary keeps draft, clear removes draft, failure/retry; no model calls')